import { readFile, writeFile, mkdir, cp } from 'node:fs/promises';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';

const folder = import.meta.dirname;
const root = resolve(folder, '..');
function replaceRequired(source, before, after) {
    if (!source.includes(before)) throw new Error(`Course edition source changed: ${before.slice(0, 80)}`);
    return source.replace(before, after);
}

export async function buildCourseVersion(output) {
    // Adapt copies only. Never write to the original templates, scripts, or resume.
    let controller = await readFile(resolve(root, 'site-controller.js'), 'utf8');
    controller = replaceRequired(controller, "if (performance.getEntriesByType('navigation')[0]?.type === 'reload')", 'if (false)');
    controller = controller.replaceAll("localStorage.setItem('theme',", "localStorage.setItem('course:theme',");
    controller = replaceRequired(controller, "const button = makeElement('button', 'nav-button', scene.label);\n            button.type = 'button';", "const button = makeElement('a', 'nav-button', scene.label);\n            button.href = `#${scene.id}`;");
    controller = replaceRequired(controller, 'socialLink.append(icon);', "socialLink.append(icon, makeElement('span', '', link.label));");
    controller = replaceRequired(controller, '/^(INPUT|TEXTAREA|SELECT)$/', '/^(INPUT|TEXTAREA|SELECT|VIDEO|AUDIO|BUTTON)$/');
    controller = replaceRequired(controller, 'anchor.append(panel);', 'window.renderCourseExtras(scene, body, makeSceneLinks);\n        anchor.append(panel);');
    // Pause media when leaving a page, including through browser history.
    controller = replaceRequired(controller, 'activeScene = scene;', "if (activeScene?.id !== scene.id) contentRoot.querySelectorAll('video, audio').forEach(media => media.pause());\n        activeScene = scene;");
    await writeFile(resolve(folder, 'controller.js'), controller);
    let preferences = await readFile(resolve(root, 'site-preferences.js'), 'utf8');
    preferences = preferences.replaceAll('portfolio:', 'course:');
    preferences = replaceRequired(preferences, "motion: 'on', quality:", "motion: 'off', quality:");
    await writeFile(resolve(folder, 'preferences.js'), preferences);
    const worker = (await readFile(resolve(root, 'fractal-worker.js'), 'utf8')).replace("'fractal-math.js'", "'/fractal-math.js'");
    await writeFile(resolve(folder, 'fractal-worker.js'), worker);

    let html = await readFile(resolve(root, 'index.html'), 'utf8');
    html = html.replace(/<!-- Generated[^]*?-->/, '<!-- Isolated course edition. Generated by terrible-version/build.mjs. -->');
    html = replaceRequired(html, '<meta charset="UTF-8">', '<meta charset="UTF-8">\n    <base href="/terrible-version/">\n    <meta name="robots" content="noindex, nofollow, noarchive">\n    <meta name="referrer" content="same-origin">');
    html = html.replaceAll("localStorage.getItem('theme')", "localStorage.getItem('course:theme')");
    html = replaceRequired(html, '<div id="blackOverlay"', '<div hidden inert aria-hidden="true" id="blackOverlay"');
    html = html.replace(/(src|href)="((?:site[^"?]*|scene-data|fractal[^"?]*|camera-travel|script|julia-preview)\.(?:js|css))(?:\?[^"\s]*)?"/g,
        (_, attr, file) => `${attr}="/${file}"`);
    html = replaceRequired(html, 'src="/site-preferences.js"', 'src="/terrible-version/preferences.js"');
    html = replaceRequired(html, 'src="/site-controller.js"', 'src="/terrible-version/controller.js"');
    html = replaceRequired(html, '<script src="/scene-data.js"></script>', '<script src="/terrible-version/content.js"></script>\n    <script src="/scene-data.js"></script>\n    <script src="/terrible-version/edition.js"></script>');
    html = replaceRequired(html, '</head>', '    <link rel="stylesheet" href="/terrible-version/edition.css">\n</head>');
    for (const match of [...html.matchAll(/(?:src|href)="(\/[^"?]+\.(?:js|css))"/g)]) {
        const hash = createHash('sha256').update(await readFile(resolve(root, `.${match[1]}`))).digest('hex').slice(0, 12);
        html = html.replace(match[0], match[0].replace(/"$/, `?v=${hash}"`));
    }
    await writeFile(resolve(folder, 'index.html'), html);
    const destination = resolve(output, 'terrible-version');
    await mkdir(destination, { recursive: true });
    for (const file of ['index.html', 'controller.js', 'preferences.js', 'fractal-worker.js', 'content.js', 'edition.js', 'edition.css', 'media']) {
        await cp(resolve(folder, file), resolve(destination, file), { recursive: true });
    }
}
